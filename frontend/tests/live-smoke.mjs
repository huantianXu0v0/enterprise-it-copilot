import {chromium,expect} from '@playwright/test';
import fs from 'node:fs/promises';
const dir=process.env.SCREENSHOT_DIR||'test-results/live';
await fs.mkdir(dir,{recursive:true});
const browser=await chromium.launch();
const page=await browser.newPage({viewport:{width:1440,height:960}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
try {
 await page.goto('http://127.0.0.1:5173');
 await expect(page.getByText('服务已连接',{exact:true})).toBeVisible({timeout:30000});
 await page.screenshot({path:dir+'/desktop.png',fullPage:true});
 await page.getByRole('button',{name:'知识空间',exact:true}).click();
 await expect(page.getByRole('button',{name:/IT知识库/})).toBeVisible();
 await expect(page.locator('tbody tr').first()).toContainText('md',{timeout:15000});
 await page.screenshot({path:dir+'/knowledge.png',fullPage:true});
 await page.getByRole('button',{name:'工具服务',exact:true}).click();
 await expect(page.locator('.tool-card')).toHaveCount(3);
 await page.locator('.tool-card').filter({hasText:'ticket_status'}).getByRole('button',{name:'测试工具'}).click();
 await page.getByRole('textbox').fill('IT-1001');
 await page.getByRole('button',{name:'执行查询',exact:true}).click();
 await expect(page.locator('.tool-result')).toContainText('处理中',{timeout:20000});
 await page.getByRole('button',{name:'关闭',exact:true}).last().click();
 await page.getByRole('button',{name:'意图编排',exact:true}).click();
 await page.getByRole('textbox',{name:'搜索意图'}).fill('it-vpn-network');
 await expect(page.locator('.intent-row')).toHaveCount(1);
 await page.screenshot({path:dir+'/intents.png',fullPage:true});
 await page.getByRole('button',{name:'开启新对话'}).click();
 await page.getByRole('textbox',{name:'输入问题'}).fill('现在北京时间几点？');
 await page.getByRole('button',{name:'发送问题'}).click();
 await expect(page.locator('.result-button')).toHaveCount(1,{timeout:180000});
 await expect(page.locator('.message.assistant')).not.toContainText('暂时没有匹配');
 await page.getByRole('button',{name:/查看处理结果/}).click();
 await expect(page.locator('.branch-card')).toContainText('已完成');
 await page.screenshot({path:dir+'/answer.png',fullPage:true});
 await page.getByRole('button',{name:'开启新对话'}).click();
 await page.getByRole('textbox',{name:'输入问题'}).fill('请查一下杭州现在的天气');
 await page.getByRole('button',{name:'发送问题'}).click();
 await expect(page.locator('.result-button')).toHaveCount(1,{timeout:180000});
 const fallback=await page.locator('.message.assistant .markdown').innerText();
 if(fallback.includes('暂时没有匹配到可处理的需求'))throw new Error('Generic fallback remains');
 console.log('Actual unsupported response:',fallback);
 const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,deviceScaleFactor:1});
 await mobile.goto('http://127.0.0.1:5173');
 await expect(mobile.getByRole('textbox',{name:'输入问题'})).toBeVisible();
 await mobile.screenshot({path:dir+'/mobile.png',fullPage:true});
 const overflow=await mobile.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
 if(overflow)throw new Error('Mobile horizontal overflow');
 await mobile.getByRole('button',{name:'打开导航'}).click();
 await expect(mobile.getByRole('button',{name:'知识空间',exact:true})).toBeVisible();
 await mobile.close();
 if(errors.length)throw new Error(errors.join('\n'));
 console.log('PASS: live navigation, knowledge list, tool call, intent search, routed chat, fallback, mobile layout');
}finally{await browser.close();}
